/**
 * Test fixtures for on-device storage (only ever imported from `*.spec.ts`, so none
 * of this reaches the app bundle).
 */

/** A fresh in-memory `Storage`, so each test starts empty and can make writes fail. */
export function memoryStorage(): Storage {
  const data = new Map<string, string>()
  return {
    get length() {
      return data.size
    },
    clear: () => data.clear(),
    getItem: (key) => data.get(key) ?? null,
    key: (index) => [...data.keys()][index] ?? null,
    removeItem: (key) => {
      data.delete(key)
    },
    setItem: (key, value) => {
      data.set(key, String(value))
    },
  }
}
